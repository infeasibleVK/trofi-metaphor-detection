#!/usr/bin/env python3
"""
Evaluate the Classical Selectional-Preference Violation (SPV) Baseline (Task 1).

Execution flow:
1. Load train, validation, and test splits generated by preprocess.py.
2. Extract grammatical subject and object arguments with spaCy and ArgumentExtractor.
3. Fit ResnikSPVModel on the training split only.
4. Perform grid search on the validation split to find optimal threshold tau* maximizing Metaphor F1.
5. Evaluate on the test split using the frozen threshold tau*.
6. Report Accuracy, Precision, Recall, F1 (metaphor class), Confusion Matrix, and POS-wise breakdown.
7. Export data/task1/spv_scores.csv (and data/task1_scores.csv) for seamless consumption by Task 3.

Reference:
- Assignment II Project 11 Guidelines (CS60075)
"""

import os
import shutil
import argparse
import logging
from typing import List, Dict, Any, Tuple
import numpy as np
import pandas as pd
from sklearn.metrics import (
    accuracy_score,
    precision_score,
    recall_score,
    f1_score,
    confusion_matrix,
    classification_report,
)
import spacy

from spv_detector import ArgumentExtractor, ResnikSPVModel, WordNetSenseProfiler

logging.basicConfig(
    level=logging.INFO,
    format="%(asctime)s [%(levelname)s] %(message)s"
)
logger = logging.getLogger(__name__)


def extract_features_from_dataframe(
    df: pd.DataFrame,
    extractor: ArgumentExtractor,
    nlp: Any,
    batch_size: int = 256
) -> List[Dict[str, Any]]:
    """
    Run spaCy and ArgumentExtractor over a DataFrame in batches for maximum efficiency.
    """
    sentences = df["sentence"].tolist()
    target_indices = df["target_idx"].tolist()
    target_verbs = df["target_verb"].tolist()
    labels = df["label"].tolist()
    sentence_ids = df["sentence_id"].tolist()

    extracted: List[Dict[str, Any]] = []

    # Process in batches using nlp.pipe
    logger.info(f"Parsing {len(sentences)} sentences with spaCy...")
    docs = list(nlp.pipe(sentences, batch_size=batch_size))

    for doc, s_id, t_idx, t_verb, lbl, sent in zip(
        docs, sentence_ids, target_indices, target_verbs, labels, sentences
    ):
        info = extractor.extract_arguments(doc, target_idx=t_idx, target_verb=t_verb)
        target_token = info["target_token"]
        pos_tag = target_token.pos_ if target_token is not None else "VERB"
        tag_detail = target_token.tag_ if target_token is not None else "VB"

        extracted.append({
            "sentence_id": s_id,
            "sentence": sent,
            "target_verb": t_verb,
            "target_index": t_idx,
            "target_pos": pos_tag,
            "target_tag": tag_detail,
            "label": lbl,
            "subj_lemma": info["subj_lemma"],
            "obj_lemma": info["obj_lemma"],
            "is_passive": info["is_passive"],
        })

    return extracted


def tune_threshold(
    model: ResnikSPVModel,
    val_records: List[Dict[str, Any]],
    num_thresholds: int = 500
) -> Tuple[float, float, Dict[str, float]]:
    """
    Perform grid search on the validation set to determine the optimal threshold tau*.
    Maximizes F1 score for the positive (Metaphor = 1) class.
    
    Decision rule:
    - If cold_start_flag == 1: predict 0 (Literal fallback, per assignment instructions).
    - Else if spv_score > tau: predict 1 (Metaphorical), else 0 (Literal).
      (Equivalent to: association_score < -tau)
    """
    val_labels = np.array([r["label"] for r in val_records])
    scored_val = []

    for r in val_records:
        res = model.score_instance(
            r["target_verb"],
            subj_lemma=r["subj_lemma"],
            obj_lemma=r["obj_lemma"]
        )
        scored_val.append(res)

    spv_scores = np.array([s["spv_score"] for s in scored_val])
    cold_flags = np.array([s["cold_start_flag"] for s in scored_val])

    # Sweep threshold range
    min_score, max_score = float(np.min(spv_scores)), float(np.max(spv_scores))
    thresholds = np.linspace(min_score - 0.5, max_score + 0.5, num_thresholds)

    best_tau = 0.0
    best_f1 = -1.0
    best_metrics = {}

    for tau in thresholds:
        preds = np.where((spv_scores > tau) & (cold_flags == 0), 1, 0)
        f1 = f1_score(val_labels, preds, pos_label=1, zero_division=0)
        if f1 > best_f1:
            best_f1 = f1
            best_tau = tau
            best_metrics = {
                "val_f1": f1,
                "val_accuracy": accuracy_score(val_labels, preds),
                "val_precision": precision_score(val_labels, preds, pos_label=1, zero_division=0),
                "val_recall": recall_score(val_labels, preds, pos_label=1, zero_division=0),
            }

    logger.info(
        f"[Validation Tuning] Optimal Threshold (tau*): {best_tau:.4f} | "
        f"Val Metaphor F1: {best_metrics['val_f1']:.4f} | "
        f"Val Prec: {best_metrics['val_precision']:.4f} | "
        f"Val Rec: {best_metrics['val_recall']:.4f} | "
        f"Val Acc: {best_metrics['val_accuracy']:.4f}"
    )

    return best_tau, best_f1, best_metrics


def evaluate_split(
    model: ResnikSPVModel,
    records: List[Dict[str, Any]],
    tau: float,
    split_name: str = "Test"
) -> Tuple[pd.DataFrame, Dict[str, Any]]:
    """
    Score instances and evaluate classification metrics on a dataset split.
    """
    labels = np.array([r["label"] for r in records])
    scored_rows = []

    for r in records:
        sc = model.score_instance(
            r["target_verb"],
            subj_lemma=r["subj_lemma"],
            obj_lemma=r["obj_lemma"]
        )
        cold = sc["cold_start_flag"]
        spv = sc["spv_score"]
        assoc = sc["association_score"]

        # Classification decision rule
        pred = 1 if (spv > tau and cold == 0) else 0

        scored_rows.append({
            "sentence_id": r["sentence_id"],
            "sentence": r["sentence"],
            "target_verb": r["target_verb"],
            "target_index": r["target_index"],
            "target_pos": r["target_pos"],
            "target_tag": r["target_tag"],
            "gold_label": r["label"],
            "spv_score": round(spv, 4),
            "association_score": round(assoc, 4),
            "task1_prediction": int(pred),
            "cold_start_flag": int(cold),
            "sps_verb": round(sc["sps_verb"], 4),
            "subj_noun": r["subj_lemma"] or "",
            "obj_noun": r["obj_lemma"] or "",
            "subj_score": round(sc["subj_score"], 4) if sc["subj_score"] is not None else None,
            "obj_score": round(sc["obj_score"], 4) if sc["obj_score"] is not None else None,
            "is_passive": int(r["is_passive"]),
        })

    df_out = pd.DataFrame(scored_rows)
    preds = df_out["task1_prediction"].values

    acc = accuracy_score(labels, preds)
    prec = precision_score(labels, preds, pos_label=1, zero_division=0)
    rec = recall_score(labels, preds, pos_label=1, zero_division=0)
    f1 = f1_score(labels, preds, pos_label=1, zero_division=0)
    macro_f1 = f1_score(labels, preds, average="macro", zero_division=0)
    cm = confusion_matrix(labels, preds)

    metrics = {
        "accuracy": acc,
        "precision": prec,
        "recall": rec,
        "f1": f1,
        "macro_f1": macro_f1,
        "confusion_matrix": cm,
        "report": classification_report(labels, preds, target_names=["Literal (0)", "Metaphor (1)"]),
    }

    logger.info(f"\n=================== {split_name} Evaluation Results ===================")
    logger.info(f"Threshold (tau*):          {tau:.4f}")
    logger.info(f"Accuracy:                  {acc:.4f} ({acc*100:.2f}%)")
    logger.info(f"Metaphor Precision:        {prec:.4f}")
    logger.info(f"Metaphor Recall:           {rec:.4f}")
    logger.info(f"Metaphor F1 Score:         {f1:.4f}")
    logger.info(f"Macro F1 Score:            {macro_f1:.4f}")
    logger.info(f"\nConfusion Matrix (Rows: Gold [0, 1], Cols: Pred [0, 1]):\n{cm}")
    logger.info(f"\nFull Classification Report:\n{metrics['report']}")

    # POS-wise F1 breakdown (as required by the assignment guidelines)
    logger.info("=== F1 Breakdown by Part-of-Speech ===")
    for pos_cat in sorted(df_out["target_pos"].unique()):
        mask = df_out["target_pos"] == pos_cat
        pos_labels = df_out.loc[mask, "gold_label"].values
        pos_preds = df_out.loc[mask, "task1_prediction"].values
        pos_f1 = f1_score(pos_labels, pos_preds, pos_label=1, zero_division=0)
        pos_acc = accuracy_score(pos_labels, pos_preds)
        logger.info(f"  POS [{pos_cat:5s}] Count: {mask.sum():3d} | F1: {pos_f1:.4f} | Acc: {pos_acc:.4f}")

    # Fine-grained verb tag breakdown
    logger.info("=== F1 Breakdown by Fine-Grained Verb Tag (Penn Treebank) ===")
    for tag_cat in sorted(df_out["target_tag"].unique()):
        mask = df_out["target_tag"] == tag_cat
        if mask.sum() >= 5:  # Only report if support >= 5
            tag_labels = df_out.loc[mask, "gold_label"].values
            tag_preds = df_out.loc[mask, "task1_prediction"].values
            tag_f1 = f1_score(tag_labels, tag_preds, pos_label=1, zero_division=0)
            logger.info(f"  Tag [{tag_cat:5s}] Count: {mask.sum():3d} | F1: {tag_f1:.4f}")

    return df_out, metrics


def main():
    parser = argparse.ArgumentParser(description="Evaluate Classical SPV Baseline for TroFi Metaphor Detection (Task 1)")
    parser.add_argument("--train_path", type=str, default="data/trofi_train.csv", help="Path to training CSV")
    parser.add_argument("--val_path", type=str, default="data/trofi_val.csv", help="Path to validation CSV")
    parser.add_argument("--test_path", type=str, default="data/trofi_test.csv", help="Path to test CSV")
    parser.add_argument("--output_scores", type=str, default="data/task1/spv_scores.csv", help="Output path for exported SPV scores")
    parser.add_argument("--alpha", type=float, default=0.1, help="Lidstone smoothing parameter")
    parser.add_argument("--profile_source", type=str, default="all", choices=["all", "literal"], help="Corpus source for SPV profiles")
    parser.add_argument("--prior_type", type=str, default="relation_specific", choices=["relation_specific", "shared"], help="Prior distribution type")
    parser.add_argument("--compare_configs", action="store_true", default=False, help="Compare profile sources on validation data only")
    args = parser.parse_args()

    for path, name in [(args.train_path, "Train"), (args.val_path, "Val"), (args.test_path, "Test")]:
        if not os.path.exists(path):
            raise FileNotFoundError(f"{name} split not found at {path}. Run code/task1/preprocess.py first.")

    logger.info("Loading spaCy model 'en_core_web_sm'...")
    nlp = spacy.load("en_core_web_sm")
    extractor = ArgumentExtractor(nlp)

    logger.info(f"Reading dataset splits:")
    train_df = pd.read_csv(args.train_path)
    val_df = pd.read_csv(args.val_path)
    test_df = pd.read_csv(args.test_path)
    logger.info(f"  Train: {len(train_df)} rows | Val: {len(val_df)} rows | Test: {len(test_df)} rows")

    # Extract syntactic arguments
    logger.info("Extracting syntactic arguments from splits...")
    train_records = extract_features_from_dataframe(train_df, extractor, nlp)
    val_records = extract_features_from_dataframe(val_df, extractor, nlp)
    test_records = extract_features_from_dataframe(test_df, extractor, nlp)

    # If requested, compare profile_source options on validation split ONLY
    if args.compare_configs:
        logger.info("\n=== Comparing Configurations on Validation Split (Test Set Untouched) ===")
        for p_src in ["all", "literal"]:
            comp_m = ResnikSPVModel(alpha=args.alpha, profile_source=p_src, prior_type=args.prior_type)
            comp_m.fit(train_records)
            tau, f1, m_metrics = tune_threshold(comp_m, val_records)
            logger.info(
                f"Validation Config [profile_source='{p_src}']: "
                f"Val F1 = {f1:.4f} | Prec = {m_metrics['val_precision']:.4f} | "
                f"Rec = {m_metrics['val_recall']:.4f} | Acc = {m_metrics['val_accuracy']:.4f} | Tau* = {tau:.4f}"
            )

    # Fit Resnik SPV Model on Train only
    model = ResnikSPVModel(alpha=args.alpha, profile_source=args.profile_source, prior_type=args.prior_type)
    model.fit(train_records)

    # Tune threshold on Validation only
    best_tau, best_f1, val_metrics = tune_threshold(model, val_records)

    # Evaluate frozen model and threshold on Test
    test_df_out, test_metrics = evaluate_split(model, test_records, tau=best_tau, split_name="Test")

    # Export SPV scores and predictions
    out_dir = os.path.dirname(args.output_scores)
    if out_dir:
        os.makedirs(out_dir, exist_ok=True)
    test_df_out.to_csv(args.output_scores, index=False)
    logger.info(f"Successfully exported Task 1 comprehensive test predictions and SPV scores to '{args.output_scores}'")

    # Score train and val splits to assist Task 3 feature augmentation
    train_df_out, _ = evaluate_split(model, train_records, tau=best_tau, split_name="Train")
    val_df_out, _ = evaluate_split(model, val_records, tau=best_tau, split_name="Val")

    train_scores_path = os.path.join(out_dir, "spv_scores_train.csv")
    val_scores_path = os.path.join(out_dir, "spv_scores_val.csv")
    test_scores_path = os.path.join(out_dir, "spv_scores_test.csv")
    all_scores_path = os.path.join(out_dir, "spv_scores_all.csv")

    train_df_out.to_csv(train_scores_path, index=False)
    val_df_out.to_csv(val_scores_path, index=False)
    test_df_out.to_csv(test_scores_path, index=False)
    all_df_out = pd.concat([train_df_out, val_df_out, test_df_out], ignore_index=True)
    all_df_out.to_csv(all_scores_path, index=False)
    logger.info(f"Exported separate split files: '{train_scores_path}', '{val_scores_path}', '{test_scores_path}', '{all_scores_path}'")

    # Distinct exports for Task 3:
    # 1. data/task1_scores.csv: continuous association & SPV scores for correlation.py
    score_cols = [
        "sentence_id", "sentence", "target_verb", "target_index",
        "gold_label", "spv_score", "association_score", "cold_start_flag",
        "subj_score", "obj_score", "sps_verb"
    ]
    root_scores_path = "data/task1_scores.csv"
    test_df_out[score_cols].to_csv(root_scores_path, index=False)
    logger.info(f"Exported dedicated score file: '{root_scores_path}' ({len(score_cols)} columns)")

    # 2. data/task1_preds.csv: discrete predictions & error flags for disagreement_analysis.py
    preds_df = pd.DataFrame({
        "sentence_id": test_df_out["sentence_id"],
        "target_verb": test_df_out["target_verb"],
        "target_index": test_df_out["target_index"],
        "sentence": test_df_out["sentence"],
        "gold_label": test_df_out["gold_label"],
        "prediction": test_df_out["task1_prediction"],
        "task1_prediction": test_df_out["task1_prediction"],
        "is_correct": (test_df_out["gold_label"] == test_df_out["task1_prediction"]).astype(int)
    })
    root_preds_path = "data/task1_preds.csv"
    preds_df.to_csv(root_preds_path, index=False)
    logger.info(f"Exported dedicated prediction file: '{root_preds_path}' ({len(preds_df.columns)} columns)")


if __name__ == "__main__":
    main()
